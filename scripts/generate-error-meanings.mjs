#!/usr/bin/env node
/**
 * Writes packages/mcp-core/src/error-meanings.ts from openapi-specs/ (REQ-XC-001
 * AC 3, ADR-0008 D3): the meaning each operation documents for each error
 * status, for both bMS releases. The specs aren't shipped with the servers, so
 * the table is generated and committed; __tests__/error-meanings.guard.test.ts
 * derives it again and fails when it drifts.
 *
 *   node scripts/generate-error-meanings.mjs
 *
 * Rule: every response with status >= 400, unless its description only repeats
 * the HTTP reason phrase ("Bad Request", "Internal Server Error").
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { STATUS_CODES } from "node:http";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RELEASES = ["25R2", "26R1"];
const OUT = join(ROOT, "packages", "mcp-core", "src", "error-meanings.ts");

const letters = (s) => s.toLowerCase().replace(/[^a-z]/g, "");
const oneLine = (s) => s.replace(/\s+/g, " ").trim();

/** key → { releases, method, domain, path, status, meaning } */
const rows = new Map();
/** key → { releases, method, domain, path }: every operation, so a lookup can pick the right route first */
const routes = new Map();
for (const release of RELEASES) {
  const dir = join(ROOT, "openapi-specs", release);
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    // 25R2 and 26R1 spell the file names differently (DefenseControl / Defensecontrol).
    const domain = file.replace(/^bConnect_/, "").replace(/\.json$/, "").toLowerCase();
    const spec = JSON.parse(readFileSync(join(dir, file), "utf8"));
    for (const [path, byMethod] of Object.entries(spec.paths ?? {})) {
      for (const [method, op] of Object.entries(byMethod)) {
        if (!op || typeof op !== "object" || !op.responses) {continue;}
        const routeKey = JSON.stringify([method.toUpperCase(), domain, path]);
        const route = routes.get(routeKey) ?? { releases: [], method: method.toUpperCase(), domain, path };
        route.releases.push(release);
        routes.set(routeKey, route);
        for (const [code, response] of Object.entries(op.responses)) {
          const status = Number(code);
          if (!(status >= 400)) {continue;}
          const meaning = oneLine(String(response.description ?? ""));
          if (meaning === "" || letters(meaning) === letters(STATUS_CODES[status] ?? "")) {continue;}
          const upper = method.toUpperCase();
          const key = JSON.stringify([upper, domain, path, status, meaning]);
          const row = rows.get(key) ?? { releases: [], method: upper, domain, path, status, meaning };
          row.releases.push(release);
          rows.set(key, row);
        }
      }
    }
  }
}

const sorted = [...rows.values()].sort((a, b) =>
  a.domain.localeCompare(b.domain) || a.path.localeCompare(b.path) ||
  a.method.localeCompare(b.method) || a.status - b.status || a.meaning.localeCompare(b.meaning));

const sortedRoutes = [...routes.values()].sort((a, b) =>
  a.domain.localeCompare(b.domain) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const q = (s) => JSON.stringify(s);
const routeLines = sortedRoutes.map((r) =>
  `  { releases: [${r.releases.map(q).join(", ")}], method: ${q(r.method)}, domain: ${q(r.domain)}, path: ${q(r.path)} },`);
const lines = sorted.map((r) =>
  `  { releases: [${r.releases.map(q).join(", ")}], method: ${q(r.method)}, domain: ${q(r.domain)}, ` +
  `path: ${q(r.path)}, status: ${r.status}, meaning: ${q(r.meaning)} },`);

writeFileSync(OUT, `/**
 * GENERATED by scripts/generate-error-meanings.mjs from openapi-specs/ — do not edit.
 * Regenerate after a spec update; __tests__/error-meanings.guard.test.ts fails when
 * this table and the specs disagree.
 *
 * The meaning each bConnect operation documents for an error status
 * (REQ-XC-001 AC 3, ADR-0008 D3).
 */

export interface DocumentedRoute {
  releases: readonly string[]; // bMS releases whose spec has this operation
  method: string;              // upper-case HTTP method
  domain: string;              // URL segment under the base URL, e.g. "endpoints"
  path: string;                // spec path template
}

export interface ErrorMeaning {
  releases: readonly string[]; // bMS releases whose spec documents this meaning
  method: string;              // upper-case HTTP method
  domain: string;              // URL segment under the base URL, e.g. "endpoints"
  path: string;                // spec path template, e.g. /v2.0/Endpoints/{id}/MaintenanceWindow
  status: number;
  meaning: string;
}

/** Every operation of both specs; a request is matched to its route before its meaning is looked up. */
export const DOCUMENTED_ROUTES: readonly DocumentedRoute[] = Object.freeze([
${routeLines.join("\n")}
]);

export const ERROR_MEANINGS: readonly ErrorMeaning[] = Object.freeze([
${lines.join("\n")}
]);
`);
console.log(`error-meanings.ts: ${sortedRoutes.length} routes, ${sorted.length} meanings`);
